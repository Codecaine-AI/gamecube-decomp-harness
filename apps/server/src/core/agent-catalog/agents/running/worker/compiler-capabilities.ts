import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Per-version trace points of the traced MWCC builds (`mwcc-native-capabilities-v1`),
 * written by `toolpacks/gamecube-decomp/compiler/mwcc_alloc/native/build.sh`. A
 * point is listed only when its source links from source in that version and
 * its event-presence check passed, so an unlisted point is unavailable, never
 * empty. The worker prompt's `<compiler>` section renders this per version.
 */
export interface CompilerCapabilities {
  schema: string;
  pin: string | null;
  /** `<ver>` (`1.2.5`, `1.2.5n`, `1.1p1`) -> the trace points that version records. */
  versions: Record<string, { points: string[] }>;
}

/** Every trace point, in the order the prompt names missing ones. */
export const TRACE_POINTS = [
  "vreg_identity",
  "interference",
  "coloring",
  "coalescing",
  "inlining",
  "cse",
  "frame",
  "scheduling",
] as const;

const TRACE_POINT_LABELS: Record<string, string> = {
  vreg_identity: "vreg identity",
  cse: "CSE",
};

export const COMPILER_CAPABILITIES_SCHEMA = "mwcc-native-capabilities-v1";

/** The repo-relative capabilities file (contract: committed copy for tests, regenerated by `build.sh`). */
export const COMPILER_CAPABILITIES_RELATIVE_PATH = "toolpacks/gamecube-decomp/compiler/mwcc_alloc/native/CAPABILITIES.json";

function repoRoot(): string {
  return resolve(import.meta.dir, "../../../../../../../..");
}

export function defaultCompilerCapabilitiesPath(): string {
  return resolve(repoRoot(), COMPILER_CAPABILITIES_RELATIVE_PATH);
}

/** Parses a capabilities document; null when it is not one. Unknown fields are ignored. */
export function parseCompilerCapabilities(value: unknown): CompilerCapabilities | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  if (record.schema !== COMPILER_CAPABILITIES_SCHEMA) return null;
  const rawVersions = record.versions;
  if (!rawVersions || typeof rawVersions !== "object" || Array.isArray(rawVersions)) return null;
  const versions: CompilerCapabilities["versions"] = {};
  for (const [version, entry] of Object.entries(rawVersions as Record<string, unknown>)) {
    const points = entry && typeof entry === "object" && Array.isArray((entry as Record<string, unknown>).points)
      ? ((entry as Record<string, unknown>).points as unknown[]).filter((point): point is string => typeof point === "string")
      : [];
    versions[version] = { points };
  }
  return { schema: COMPILER_CAPABILITIES_SCHEMA, pin: typeof record.pin === "string" ? record.pin : null, versions };
}

const cache = new Map<string, CompilerCapabilities | null>();

/**
 * The capabilities file, or null when it is absent or unreadable (no traced
 * compiler has been built and validated yet). Never throws.
 */
export function loadCompilerCapabilities(path = defaultCompilerCapabilitiesPath()): CompilerCapabilities | null {
  if (cache.has(path)) return cache.get(path) ?? null;
  let parsed: CompilerCapabilities | null = null;
  try {
    if (existsSync(path)) parsed = parseCompilerCapabilities(JSON.parse(readFileSync(path, "utf8")));
  } catch {
    parsed = null;
  }
  cache.set(path, parsed);
  return parsed;
}

function joinWords(words: string[]): string {
  if (words.length <= 1) return words.join("");
  return `${words.slice(0, -1).join(", ")} or ${words[words.length - 1]}`;
}

/** Display order: the versions the games use, most used first; any other version after them. */
const VERSION_ORDER = ["1.2.5", "1.2.5n", "1.1p1"];

function versionOrder(left: string, right: string): number {
  const rank = (version: string) => (VERSION_ORDER.includes(version) ? VERSION_ORDER.indexOf(version) : VERSION_ORDER.length);
  return rank(left) - rank(right) || left.localeCompare(right);
}

/**
 * One line per compiler version: which native trace points it lacks, e.g.
 * `GC/1.2.5n: no frame or scheduling`. Null capabilities render the single
 * "not provisioned" line.
 */
export function tracePointAvailabilityLines(capabilities: CompilerCapabilities | null): string[] {
  const versions = capabilities ? Object.keys(capabilities.versions).sort(versionOrder) : [];
  if (versions.length === 0) {
    return ["No traced compiler is provisioned: every native trace point is unavailable; native captures and source comparisons report unavailable."];
  }
  return versions.map((version) => {
    const have = new Set(capabilities!.versions[version]!.points);
    const missing = TRACE_POINTS.filter((point) => !have.has(point)).map((point) => TRACE_POINT_LABELS[point] ?? point);
    return `GC/${version}: ${missing.length === 0 ? "all" : missing.length === TRACE_POINTS.length ? "none" : `all except ${joinWords(missing)}`}`;
  });
}
